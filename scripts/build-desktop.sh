#!/usr/bin/env bash
# Build a release "desktop" version of Harness into dist/ and (re)install its launcher.
#
#   scripts/build-desktop.sh            # build + install menu entry
#   scripts/build-desktop.sh --no-menu  # build only
#
# dist/harness      launcher: sets LD_LIBRARY_PATH for the libs gpui dlopens (wayland,
#                   xkbcommon, vulkan, fontconfig...) — captured from shell.nix at build time —
#                   then execs dist/harness-bin. `harness [DIR]` uses DIR as the chat workspace.
# dist/harness-bin  the release binary.
# dist/VERSION      build stamp (git-less: date + content hash of the binary).
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

nix-shell shell.nix --run 'cargo build --release --bin harness' </dev/null
libs="$(nix-shell shell.nix --run 'printf %s "$LD_LIBRARY_PATH"' </dev/null)"

mkdir -p dist
install -m 755 target/release/harness dist/harness-bin.new
mv -f dist/harness-bin.new dist/harness-bin
cp packaging/harness.svg dist/harness.svg

cat > dist/harness <<LAUNCHER
#!/usr/bin/env bash
# Generated by scripts/build-desktop.sh — do not edit.
here="\$(cd "\$(dirname "\$(readlink -f "\$0")")" && pwd)"
export LD_LIBRARY_PATH="$libs:/run/opengl-driver/lib\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
if [ \$# -gt 0 ] && [ -d "\$1" ]; then export HARNESS_WORKSPACE="\$(cd "\$1" && pwd)"; shift; fi
exec "\$here/harness-bin" "\$@"
LAUNCHER
chmod 755 dist/harness

stamp="$(date '+%Y-%m-%d %H:%M') $(sha256sum dist/harness-bin | cut -c1-12)"
echo "$stamp" > dist/VERSION

if [ "${1:-}" != "--no-menu" ]; then
  apps="${XDG_DATA_HOME:-$HOME/.local/share}/applications"
  mkdir -p "$apps"
  cat > "$apps/harness.desktop" <<DESKTOP
[Desktop Entry]
Type=Application
Name=Harness
GenericName=Agent pipeline editor
Comment=Agent pipelines, review queue and a real coding-agent chat (GPUI)
Exec=$root/dist/harness %f
Icon=$root/dist/harness.svg
Terminal=false
Categories=Development;
StartupWMClass=harness-demo
DESKTOP
  command -v update-desktop-database >/dev/null && update-desktop-database "$apps" 2>/dev/null || true
fi
echo "built: $root/dist/harness ($stamp)"
