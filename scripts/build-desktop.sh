#!/usr/bin/env bash
# Build a release "desktop" version of the rewritten Harness into dist/ and (re)install its
# launcher, next to the old app, which stays at dist/harness until the rewrite replaces it.
#
#   scripts/build-desktop.sh            # build + install menu entry "Harness Next"
#   scripts/build-desktop.sh --no-menu  # build only
#
# dist/harness-next      launcher: sets LD_LIBRARY_PATH for the libs gpui dlopens (wayland,
#                        xkbcommon, vulkan, fontconfig...) — captured from shell.nix at build
#                        time — then execs dist/harness-next-bin.
# dist/harness-next-bin  the release binary.
# dist/harness-cli       the command-line client (same launcher treatment is not needed).
# dist/VERSION-next      build stamp (date + content hash of the binary).
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

nix-shell shell.nix --run 'cargo build --release --bin harness --bin harness-cli' </dev/null
libs="$(nix-shell shell.nix --run 'printf %s "$LD_LIBRARY_PATH"' </dev/null)"

mkdir -p dist
install -m 755 target/release/harness dist/harness-next-bin.new
mv -f dist/harness-next-bin.new dist/harness-next-bin
install -m 755 target/release/harness-cli dist/harness-cli.new
mv -f dist/harness-cli.new dist/harness-cli
cp packaging/harness.svg dist/harness.svg

cat > dist/harness-next <<LAUNCHER
#!/usr/bin/env bash
# Generated by scripts/build-desktop.sh — do not edit.
here="\$(cd "\$(dirname "\$(readlink -f "\$0")")" && pwd)"
export LD_LIBRARY_PATH="$libs:/run/opengl-driver/lib\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
exec "\$here/harness-next-bin" "\$@"
LAUNCHER
chmod 755 dist/harness-next

stamp="$(date '+%Y-%m-%d %H:%M') $(sha256sum dist/harness-next-bin | cut -c1-12)"
echo "$stamp" > dist/VERSION-next

if [ "${1:-}" != "--no-menu" ]; then
  apps="${XDG_DATA_HOME:-$HOME/.local/share}/applications"
  mkdir -p "$apps"
  cat > "$apps/harness-next.desktop" <<DESKTOP
[Desktop Entry]
Type=Application
Name=Harness Next
GenericName=Coding-agent harness
Comment=Chat, issues, agent pipelines and an inbox (the rewrite, next to the old app)
Exec=$root/dist/harness-next
Icon=$root/dist/harness.svg
Terminal=false
Categories=Development;
StartupWMClass=harness
DESKTOP
  command -v update-desktop-database >/dev/null && update-desktop-database "$apps" 2>/dev/null || true
fi
echo "built: $root/dist/harness-next ($stamp)"
